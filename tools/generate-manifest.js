import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const OUTPUT_FILE = path.join(ROOT_DIR, 'public', 'assets-manifest.js');

const DIRS_TO_SCAN = ['js', 'css', 'public/assets'];
const FILES_TO_INCLUDE = ['index.html', 'manifest.json'];

function scanDirectory(dir, fileList) {
    const fullPath = path.join(ROOT_DIR, dir);
    if (!fs.existsSync(fullPath)) return fileList;

    const files = fs.readdirSync(fullPath);

    files.forEach(file => {
        if (file.startsWith('.')) return; // Skip hidden files

        const filePath = path.join(fullPath, file);
        const stat = fs.statSync(filePath);

        if (stat.isDirectory()) {
            scanDirectory(path.join(dir, file), fileList);
        } else {
            // Convert to relative path from root, ensuring forward slashes
            // But verify it's not the OUTPUT_FILE or sw.js
            if (filePath === OUTPUT_FILE) return;

            let relativePath = path.join(dir, file).replace(/\\/g, '/');
            if (relativePath.startsWith('public/')) {
                relativePath = relativePath.substring(7); // Remove 'public/'
            }
            fileList.push('./' + relativePath);
        }
    });

    return fileList;
}

function generate() {
    let allFiles = [];

    // Scan directories
    DIRS_TO_SCAN.forEach(dir => {
        scanDirectory(dir, allFiles);
    });

    // Add specific files
    FILES_TO_INCLUDE.forEach(file => {
        allFiles.push('./' + file);
    });

    // Create the content
    const content = `// Auto-generated by tools/generate-manifest.js
self.MANIFEST = ${JSON.stringify(allFiles, null, 4)};
`;

    fs.writeFileSync(OUTPUT_FILE, content);
    console.log(`Manifest generated at ${OUTPUT_FILE} with ${allFiles.length} assets.`);
}

generate();
